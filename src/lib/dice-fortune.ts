export function rollDice(): { die1: number; die2: number; sum: number; meaning: string } {
  const die1 = Math.floor(Math.random() * 6) + 1;
  const die2 = Math.floor(Math.random() * 6) + 1;
  const sum = die1 + die2;
  return { die1, die2, sum, meaning: DICE_MEANINGS[sum] };
}
